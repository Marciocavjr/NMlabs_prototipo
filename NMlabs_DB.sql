create table public.leituras_ambientais (
  id bigint generated by default as identity not null,
  temperatura numeric(5, 2) not null,
  umidade numeric(5, 2) not null,
  data_registro date null default CURRENT_DATE,
  hora_registro time without time zone null default CURRENT_TIME,
  log_status text not null,
  created_at timestamp with time zone not null default timezone ('utc'::text, now()),
  constraint leituras_ambientais_pkey primary key (id)
) TABLESPACE pg_default;